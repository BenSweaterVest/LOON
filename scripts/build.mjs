#!/usr/bin/env node
/**
 * Static site build. Cloudflare Pages runs this on every push:
 *   build command: npm run build     output directory: dist
 *
 * Reads published content from content/ and writes:
 *   dist/<id>/index.html    one page per published page
 *   dist/index.html         the home page (or a page list)
 *   dist/404.html, dist/sitemap.xml, dist/robots.txt
 *   dist/media/*            published images
 *   dist/admin/*, dist/assets/*   static app files from public/
 *   dist/assets/shared/*    renderer modules for the admin preview
 *   dist/_headers, dist/_routes.json
 *
 * Usage: node scripts/build.mjs [--out dir] [--content dir]
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { renderDocument, renderPage, themeCss } from '../src/shared/render.js';
import { DEFAULT_SETTINGS, validateSettings } from '../src/shared/site.js';
import { escapeHtml } from '../src/shared/markdown.js';
import { isValidPageId } from '../src/shared/page-id.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

function arg(name, fallback) {
    const i = process.argv.indexOf(name);
    return i > -1 ? path.resolve(process.argv[i + 1]) : fallback;
}

const SITE_POLICY = [
    "default-src 'self'",
    "img-src 'self' https: data:",
    "style-src 'self'",
    "script-src 'self'",
    "connect-src 'self'",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'"
].join('; ');

const ADMIN_POLICY = [
    "default-src 'self'",
    "img-src 'self' https: data: blob:",
    "style-src 'self'",
    "script-src 'self'",
    "connect-src 'self'",
    "worker-src 'self' blob:",
    "frame-src 'self'",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'"
].join('; ');

export const HEADERS = `# Generated by scripts/build.mjs
/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=()
  X-Frame-Options: DENY
  Strict-Transport-Security: max-age=31536000
  Content-Security-Policy: ${SITE_POLICY}

/admin/*
  ! Content-Security-Policy
  Content-Security-Policy: ${ADMIN_POLICY}
  Cache-Control: no-store
  X-Robots-Tag: noindex

/assets/*
  Cache-Control: public, max-age=3600

/media/*
  Cache-Control: public, max-age=31536000, immutable
`;

function copyDir(from, to) {
    if (!fs.existsSync(from)) return 0;
    let count = 0;
    fs.mkdirSync(to, { recursive: true });
    for (const entry of fs.readdirSync(from, { withFileTypes: true })) {
        if (entry.name.startsWith('.')) continue;
        const src = path.join(from, entry.name);
        const dest = path.join(to, entry.name);
        if (entry.isDirectory()) count += copyDir(src, dest);
        else { fs.copyFileSync(src, dest); count++; }
    }
    return count;
}

function write(file, text) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, text);
}

function readJson(file, fallback) {
    try {
        return JSON.parse(fs.readFileSync(file, 'utf8'));
    } catch (err) {
        if (err.code === 'ENOENT') return fallback;
        throw new Error(`Could not read ${path.relative(ROOT, file)}: ${err.message}`);
    }
}

export function loadContent(contentDir) {
    const settingsRaw = readJson(path.join(contentDir, 'site.json'), {});
    const { settings, errors } = validateSettings({ ...DEFAULT_SETTINGS, ...settingsRaw });
    if (errors.length) console.warn(`site.json: ${errors.join('; ')} (using defaults for invalid values)`);

    const pagesDir = path.join(contentDir, 'pages');
    const pages = fs.existsSync(pagesDir)
        ? fs.readdirSync(pagesDir).filter((f) => f.endsWith('.json')).sort().map((f) => readJson(path.join(pagesDir, f)))
        : [];
    const valid = pages.filter((p) => {
        if (!p || !isValidPageId(p.id) || !p.schema || !p.data) {
            console.warn(`Skipping malformed page file: ${p?.id ?? 'unknown'}`);
            return false;
        }
        return true;
    });
    return { settings, pages: valid };
}

function indexBody(settings, pages) {
    if (!pages.length) {
        return `<article class="page"><header class="hero"><h1>${escapeHtml(settings.siteName)}</h1>
<p class="lede">This site has no published pages yet.</p></header>
<p>If you run this site, <a href="/admin/">sign in to the editor</a> to create and publish your first page.</p></article>`;
    }
    const items = [...pages]
        .sort((a, b) => a.title.localeCompare(b.title))
        .map((p) => `<li><a href="/${p.id}/">${escapeHtml(p.title)}<span>/${p.id}/</span></a></li>`)
        .join('');
    return `<article class="page"><header class="hero"><h1>${escapeHtml(settings.siteName)}</h1>${settings.tagline ? `<p class="lede">${escapeHtml(settings.tagline)}</p>` : ''}</header><ul class="page-list">${items}</ul></article>`;
}

export function build({ outDir = path.join(ROOT, 'dist'), contentDir = path.join(ROOT, 'content'), siteUrl = process.env.SITE_URL || '' } = {}) {
    const started = Date.now();
    siteUrl = siteUrl.replace(/\/+$/, '');
    fs.rmSync(outDir, { recursive: true, force: true });
    fs.mkdirSync(outDir, { recursive: true });

    copyDir(path.join(ROOT, 'public'), outDir);
    copyDir(path.join(ROOT, 'src', 'shared'), path.join(outDir, 'assets', 'shared'));
    const mediaCount = copyDir(path.join(contentDir, 'media'), path.join(outDir, 'media'));

    const { settings, pages } = loadContent(contentDir);
    write(path.join(outDir, 'assets', 'theme.css'), themeCss(settings));

    const home = pages.find((p) => p.id === settings.homePage);
    for (const page of pages) {
        write(path.join(outDir, page.id, 'index.html'), renderPage(page, settings, { siteUrl }));
    }
    write(
        path.join(outDir, 'index.html'),
        home
            ? renderPage(home, settings, { siteUrl, isHome: true })
            : renderDocument({ settings, title: settings.siteName, description: settings.tagline, bodyHtml: indexBody(settings, pages), canonical: siteUrl ? `${siteUrl}/` : null })
    );
    write(path.join(outDir, '404.html'), renderDocument({
        settings,
        title: 'Page not found',
        noindex: true,
        bodyHtml: '<article class="page"><header class="hero"><h1>Page not found</h1><p class="lede">The page you were looking for does not exist or is no longer published.</p></header><p><a class="button" href="/">Go to the home page</a></p></article>'
    }));

    if (siteUrl) {
        const urls = [`${siteUrl}/`, ...pages.filter((p) => p !== home).map((p) => `${siteUrl}/${p.id}/`)];
        const lastmod = new Map(pages.map((p) => [p === home ? `${siteUrl}/` : `${siteUrl}/${p.id}/`, p.publishedAt]));
        write(path.join(outDir, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map((u) => `  <url><loc>${escapeHtml(u)}</loc>${lastmod.get(u) ? `<lastmod>${new Date(lastmod.get(u)).toISOString().slice(0, 10)}</lastmod>` : ''}</url>`).join('\n')}
</urlset>
`);
    }
    write(path.join(outDir, 'robots.txt'), `User-agent: *\nDisallow: /admin/\nDisallow: /api/\n${siteUrl ? `Sitemap: ${siteUrl}/sitemap.xml\n` : ''}`);
    write(path.join(outDir, '_headers'), HEADERS);
    write(path.join(outDir, '_redirects'), '/admin.html /admin/ 301\n/admin /admin/ 301\n');
    // Only /api/* runs a Function; every other request is a free static asset.
    write(path.join(outDir, '_routes.json'), `${JSON.stringify({ version: 1, include: ['/api/*'], exclude: [] }, null, 2)}\n`);

    return { pages: pages.length, media: mediaCount, home: home?.id ?? null, ms: Date.now() - started, outDir };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const result = build({ outDir: arg('--out', undefined), contentDir: arg('--content', undefined) });
    console.log(`Built ${result.pages} page(s), ${result.media} media file(s) into ${path.relative(process.cwd(), result.outDir) || '.'} in ${result.ms}ms${result.home ? ` (home: ${result.home})` : ''}`);
}
